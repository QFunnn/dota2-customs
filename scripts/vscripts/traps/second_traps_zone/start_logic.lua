function EnablePendulum(triggerName)
	if isPendulumReady == true then
		isPendulumReady = false
		EmitGlobalSound("Conquest.Pendulum.Trigger")
		EmitGlobalSound("tutorial_rockslide")
		EmitGlobalSound("Conquest.Pendulum.Scrape")
		local pendulumTrigger = triggerName .. "_trigger"
		local pendulumModel = triggerName .. "_model"
		DoEntFire(pendulumModel, "SetAnimation", "pendulum_swing", 0, self, self)
		DoEntFire(triggerName .. "_debris", "Start", "", 0, self, self)
		DoEntFire(triggerName .. "_shake", "StartShake", "", 0, self, self)
		DoEntFire(pendulumTrigger, "Enable", "", 4, self, self)
		DoEntFire(pendulumTrigger, "Disable", "", 9, self, self)
		DoEntFire(triggerName .. "_shake", "StopShake", "", 16, self, self)
		DoEntFire(triggerName .. "_debris", "Stop", "", 16, self, self)
		local trapName = triggerName .. "_npc"
		print(trapName)
		local npc = Entities:FindByName(nil, trapName)
		npc:SetContextThink("DisableTrap", function()
			return DisablePendulum(triggerName)
		end, 5)
	end
	return -1
end

function DisablePendulum(triggerName)
	isPendulumReady = true
	if triggerCounter > 0 then
		local trapName = triggerName .. "_npc"
		local npc = Entities:FindByName(nil, trapName)
		-- npc:SetContextThink( "EnableTrap", function() return EnablePendulum( triggerName ) end, 0 )
		return 0
	end
end

function ResetTrapModel()
	print("pendulum RESET")
	triggerActive = true
end

function Fire(trigger)
	print("Pendulum has hit a hero!")
	local triggerName = thisEntity:GetName()
	local target = Entities:FindByName(nil, triggerName .. "_target")
	local level = trigger.activator:GetLevel()
	local hero = trigger.activator:GetName()
	local heroIndex = trigger.activator:GetEntityIndex()
	local heroHandle = EntIndexToHScript(heroIndex)
	if heroHandle:IsOutOfGame() == true then
		return
	end

	if heroHandle ~= nil then
		if not heroHandle:FindAbilityByName("sasori_red_secret_technique") then
			local pendulumTrap = thisEntity:FindAbilityByName("pendulum_trap")
			local killEffects = ParticleManager:CreateParticle(
				"particles/units/heroes/hero_life_stealer/life_stealer_infest_emerge_blood01.vpcf",
				PATTACH_POINT,
				heroHandle
			)
			ParticleManager:SetParticleControlEnt(
				killEffects,
				0,
				heroHandle,
				PATTACH_POINT,
				"attach_hitloc",
				heroHandle:GetAbsOrigin(),
				false
			)
			heroHandle:Attribute_SetIntValue("effectsID", killEffects)
			EmitSoundOn("Conquest.Pendulum.Target", heroHandle)
			local killerEntity = thisEntity
			if thisEntity.KillerToCredit ~= nil then
				killerEntity = thisEntity.KillerToCredit
			end
			heroHandle:Kill(nil, killerEntity)
		end
	end
end