function SetModifierProperty(g, h, i, j)
	if not IsValid(g) then
		return
	end
	local k = EOMModifierFunctionIsPlayerProperty[i]
	if k then
		local l = g:GetPlayerOwnerID()
		if l ~= -1 then
			local m = MODIFIER_PROPERTY_PLAYER_DATA
			local n = l
			local o = MODIFIER_PROPERTY_PLAYER_DATA[l]
			if o == nil then
				o = {}
			end
			m[n] = o
			g = MODIFIER_PROPERTY_PLAYER_DATA[l]
		else
			return
		end
	end
	if g.tPropertyValues == nil then
		g.tPropertyValues = {}
	end
	if g.tPropertyValues[i] == nil then
		g.tPropertyValues[i] = {}
	end
	local p = g.tPropertyValues[i]
	local q = EOMModifierFunctionSettleCallback[i]
	local r = EOMModifierFunctionCheckValueCallback[i]
	p[h] = j
	p.fValue = 0
	if type(q) == "function" then
		p.fValue = q()
	end
	for h, s in pairs(p) do
		if type(h) == "table" then
			if type(r) == "function" then
				local t = r(s)
				if t == nil then
					t = s
				end
				s = t
			end
			if type(q) == "function" then
				p.fValue = q(p.fValue, s)
			else
				p.fValue = p.fValue + s
			end
		end
	end
	if p.fValue == ZERO_VALUE then
		p.fValue = 0
	end
end
function RegisterModifierProperty(g, h, i)
	if not IsValid(g) then
		return
	end
	local k = EOMModifierFunctionIsPlayerProperty[i]
	if k then
		local l = g:GetPlayerOwnerID()
		if l ~= -1 then
			local u = MODIFIER_PROPERTY_PLAYER_DATA
			local v = l
			local w = MODIFIER_PROPERTY_PLAYER_DATA[l]
			if w == nil then
				w = {}
			end
			u[v] = w
			g = MODIFIER_PROPERTY_PLAYER_DATA[l]
		else
			return
		end
	end
	if g.tPropertyModifers == nil then
		g.tPropertyModifers = {}
	end
	if g.tPropertyModifers[i] == nil then
		g.tPropertyModifers[i] = {}
	end
	local x = g.tPropertyModifers[i]
	for y = #x, 1, -1 do
		local z = x[y]
		if not IsValid(z) then
			table.remove(x, y)
		end
	end
	x[#x + 1] = h
end
