function GetBaseAttackDamage(g, J)
	return math.max(
		1,
		(
			GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACK_DAMAGE_BASE, J)
			+ GetOriginalBaseAttackDamage(g)
		)
			* (
				1
				+ GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACK_DAMAGE_BASE_PERCENTAGE, J)
					* 0.01
			)
	)
end
function GetAttackDamage(g, J, a4, a5)
	local a6 = GetBaseAttackDamage(g, J)
	local a7 = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACK_DAMAGE_BONUS, J)
	local a8 = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACK_DAMAGE_BONUS_STEAL, J)
	local a9 = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACK_DAMAGE_TOTAL_PERCENTAGE, J)
	local j = (a6 + a7) * (1 + a9 * 0.01)
	if not a4 then
		j = j + a8
	end
	if a5 then
		j = j - a6
	end
	return math.max(a5 and 0 or 1, j)
end
