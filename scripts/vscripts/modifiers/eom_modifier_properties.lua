function GetAttackspeed(g, J)
	local af = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACKSPEED_OVERRIDE, J)
	local am = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACKSPEED_FORCE_OVERRIDE, J)
	if am > 0 or af ~= 0 then
		return af
	end
	local ac = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACKSPEED_BASE, J)
	local ad = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACKSPEED_BONUS, J)
	local ak = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACKSPEED_BONUS_PERCENTAGE, J)
	local al = GetModifierProperty(g, EOMModifierFunction.EOM_MODIFIER_PROPERTY_ATTACKSPEED_TOTAL_PERCENTAGE, J)
	local j = ac + UNIT_BASE_ATTACK_SPEED
	if ad > 0 then
		j = j + ad * (1 + ak * 0.01)
	else
		if ak < 0 then
			j = j + ad * (1 + e(-ak) * 0.01)
		else
			j = j + ad
		end
	end
	j = math.max(UNIT_MIN_ATTACK_SPEED, j * (1 + al * 0.01))
	j = j - UNIT_BASE_ATTACK_SPEED
	return j
