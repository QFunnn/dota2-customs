function GetModifierProperty(g, i, J)
	local k = EOMModifierFunctionIsPlayerProperty[i]
	if not k and not IsValid(g) then
		return 0
	end
	if k and type(g) == "number" then
		local l = g
		if l ~= -1 then
			local K = MODIFIER_PROPERTY_PLAYER_DATA
			local L = l
			local M = MODIFIER_PROPERTY_PLAYER_DATA[l]
			if M == nil then
				M = {}
			end
			K[L] = M
			g = MODIFIER_PROPERTY_PLAYER_DATA[l]
		else
			return 0
		end
	end
	if g.tPropertyModifers == nil then
		g.tPropertyModifers = {}
	end
	if g.tPropertyModifers[i] == nil then
		g.tPropertyModifers[i] = {}
	end
	if g.tPropertyValues == nil then
		g.tPropertyValues = {}
	end
	if g.tPropertyValues[i] == nil then
		g.tPropertyValues[i] = {}
	end
	local x = g.tPropertyModifers[i]
	local p = g.tPropertyValues[i]
	local q = EOMModifierFunctionSettleCallback[i]
	local N = EOMModifierFunctionUseModifierPriority[i]
	local r = EOMModifierFunctionCheckValueCallback[i]
	local O = EOMModifierFunctionName[i]
	local P = p.fValue
	if P ~= nil and type(r) == "function" then
		local Q = r(P, J)
		if Q == nil then
			Q = P
		end
		P = Q
	end
	local R = P
	if R == nil then
		R = 0
	end
	local S = R
	if type(q) == "function" then
		S = q()
		if P ~= nil then
			S = q(S, P)
		end
	end
	local T = MODIFIER_PRIORITY_LOW
	for y = #x, 1, -1 do
		local h = x[y]
		if IsValid(h) and type(h[O]) == "function" then
			local s = h[O](h, J)
			if s ~= nil then
				if type(r) == "function" then
					local U = r(s, J)
					if U == nil then
						U = s
					end
					s = U
				end
				if N then
					local V = h:GetPriority() or MODIFIER_PRIORITY_NORMAL
					if V >= T then
						T = V
						S = s
					end
				elseif type(q) == "function" then
					local W
					if i == EOMModifierFunction.EOM_MODIFIER_PROPERTY_CUSTOM_SHOP_REFRESH_LIST then
						W = q(S, s, J)
					else
						W = q(S, s)
					end
					S = W
				else
					S = S + s
				end
			end
		else
			table.remove(x, y)
		end
	end
	if S == ZERO_VALUE then
		S = 0
	end
	return S
end
function GetModifierPropertyWithPriority(g, i, J)
	if not IsValid(g) then
		return 0
	end
	g = g
	if g.tPropertyModifers == nil then
		g.tPropertyModifers = {}
	end
	if g.tPropertyModifers[i] == nil then
		g.tPropertyModifers[i] = {}
	end
	local x = g.tPropertyModifers[i]
	local O = EOMModifierFunctionName[i]
	for y = #x, 1, -1 do
		local h = x[y]
		if IsValid(h) and type(h[O]) == "function" then
			local s = h[O](h, J)
			if s and s > 0 then
				return s
			end
		else
			table.remove(x, y)
		end
	end
	return 0
end
