function GetWispAttackInterval(ap, aa)
	if aa == nil then
		aa = false
	end
	if not aa then
		local ab = GetModifierProperty(ap, EOMModifierFunction.EOM_MODIFIER_PROPERTY_WISP_ATTACK_INTERVAL_CONSTANT)
		if ab > 0 then
			return math.max(ab, WISP_MIN_ATTACK_RATE)
		end
	end
	return math.max(
		WISP_ATTACK_RATE + GetModifierProperty(ap, EOMModifierFunction.EOM_MODIFIER_PROPERTY_WISP_ATTACK_INTERVAL_BONUS),
		WISP_MIN_ATTACK_RATE
	)
end
