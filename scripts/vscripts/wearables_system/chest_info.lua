function SortChestPoolItems(pool)
	for _, chest in pairs(pool) do
		local normal_items = {}
		local chance_items = {}
		for _, item in pairs(chest.chest_items) do
			if item.chance ~= nil then
				table.insert(chance_items, item)
			else
				table.insert(normal_items, item)
			end
		end
		table.sort(chance_items, function(a, b)
			return a.chance > b.chance
		end)
		local sorted_items = {}
		for _, item in pairs(normal_items) do
			table.insert(sorted_items, item)
		end
		for _, item in pairs(chance_items) do
			table.insert(sorted_items, item)
		end
		chest.chest_items = sorted_items
	end
end

